/** Every problem with the hand-written tool facts, or none. */
export function factProblems(): string[] {
  const problems: string[] = [];
  for (const service of SERVICES) {
    const names = new Set(service.tools.map((tool) => tool.name));
    for (const name of names) {
      if (!Object.hasOwn(service.facts, name)) {
        problems.push(
          `${service.provider}: tool ${name} has no entry in scripts/lib/rules-reference.ts`,
        );
      }
    }
    for (const name of Object.keys(service.facts)) {
      if (!names.has(name)) problems.push(`${service.provider}: ${name} is not a tool any more`);
    }
  }
  return problems;
}

function row(cells: readonly string[]): string {
  return `| ${cells.map((cell) => (cell === "" ? " " : cell)).join(" | ")} |`;
}

function serviceTable(service: Service): string {
  const lines = [
    `### ${service.title}`,
    "",
    `Provider \`${service.provider}\`.${service.note === undefined ? "" : ` ${service.note}`}`,
    "",
    row(["Tool", "Kind", "Action", "Rules also see"]),
    row(["---", "---", "---", "---"]),
  ];
  for (const tool of service.tools) {
    const facts = service.facts[tool.name] ?? none;
    const kind = tool.annotations?.readOnlyHint === true ? "read" : "write";
    lines.push(row([`\`${tool.name}\``, kind, facts.action || "none", facts.sees]));
  }
  return lines.join("\n");
}

function ghTable(): string {
  const byAction = new Map<string, { kind: string; commands: string[] }>();
  for (const [command, mapping] of Object.entries(GH_ACTIONS)) {
    const entry = byAction.get(mapping.action) ?? { kind: mapping.kind, commands: [] };
    entry.commands.push(`\`gh ${command}\``);
    byAction.set(mapping.action, entry);
  }
  const lines = [
    "### gh",
    "",
    "A CLI account for `gh` has provider `cli:gh`. A command that takes `-R` must be given it, and its value becomes `repo` (lower case). A `gh pr merge` that lands `.github/workflows/` or `.github/actions/` files is `github.workflow.merge` and persistence, like the GitHub service's merge.",
    "",
    row(["Action", "Kind", "Commands"]),
    row(["---", "---", "---"]),
  ];
  for (const [action, { kind, commands }] of byAction) {
    lines.push(row([`\`${action}\``, kind, commands.join(", ")]));
  }
  lines.push(
    "",
    `Persistence, so only a rule naming the \`tool\` (\`tool: gh secret set\`), or for \`gh api\` its action \`github.api\`, admits them: ${[...GH_PERSISTENCE].map((c) => `\`gh ${c}\``).join(", ")}.`,
    "",
    `Always refused, because they run code from the checkout with the token set: ${[...GH_RUNS_REPO_CODE].map((c) => `\`gh ${c}\``).join(", ")}.`,
    "",
    "Any other `gh` command has no action and no kind: match it with `command`, `verb`, `subcommand`, `flags.*` or `argv`.",
  );
  return lines.join("\n");
}

function kubectlTable(): string {
  return [
    "### kubectl",
    "",
    "A CLI account for `kubectl` has provider `cli:kubectl`. Every command's action is `kubectl.<verb>` (`kubectl.get`, `kubectl.delete`), and flags are named by their long form, so `-n prod` is `flags.namespace: prod`.",
    "",
    `Kind \`read\` for: ${[...KUBECTL_READS].map((c) => `\`kubectl ${c}\``).join(", ")}. Every other command is \`write\`.`,
  ].join("\n");
}

/** The generated part of the page, between the markers. */
export function renderServiceTables(): string {
  const problems = factProblems();
  if (problems.length > 0) throw new Error(problems.join("\n"));
  return [...SERVICES.map(serviceTable), ghTable(), kubectlTable()].join("\n\n");
}

/** `doc` with its generated part replaced by `rendered`. */
export function withGenerated(doc: string, rendered: string): string {
  const begin = doc.indexOf(BEGIN_MARKER);
  const end = doc.indexOf(END_MARKER);
  if (begin < 0 || end < begin) throw new Error("docs/rules-reference.md has no generated markers");
  return `${doc.slice(0, begin + BEGIN_MARKER.length)}\n\n${rendered}\n\n${doc.slice(end)}`;
}
