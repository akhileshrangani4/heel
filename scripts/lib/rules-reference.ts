/** What one tool's call carries for rules, besides account, provider, agent, tool and args. */
interface ToolFacts {
  /** The action, or how it is chosen; empty for a read with no action. */
  action: string;
  /** Other match keys the call sets. */
  sees: string;
}

interface Service {
  title: string;
  provider: string;
  tools: readonly Tool[];
  facts: Readonly<Record<string, ToolFacts>>;
  /** One line under the table. */
  note?: string;
}

